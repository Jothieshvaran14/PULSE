import fs from "node:fs/promises";
import path from "node:path";
import { logger } from "../lib/logger.js";

export interface GenerateOptions {
  buildCommand?: string;
  startCommand?: string;
  outputDirectory?: string;
  packageManager?: string;
  nodeVersion?: string;
  port?: number;
}

type PackageManager = "npm" | "yarn" | "pnpm" | "bun";

const LOCKFILES: Record<PackageManager, string> = {
  npm: "package-lock.json",
  yarn: "yarn.lock",
  pnpm: "pnpm-lock.yaml",
  bun: "bun.lockb",
};

const NODE_VERSION_DEFAULT = "20";
const PYTHON_VERSION = "3.12";

/**
 * Detects which lockfile exists in the workspace directory.
 * Returns null if no lockfile is found (falls back to npm).
 */
async function detectLockfile(workspacePath: string): Promise<PackageManager> {
  for (const [pm, file] of Object.entries(LOCKFILES) as [PackageManager, string][]) {
    try {
      await fs.access(path.join(workspacePath, file));
      logger.info({ lockfile: file, packageManager: pm }, "Detected lockfile");
      return pm;
    } catch {
      // lockfile not found, try next
    }
  }
  logger.info("No lockfile found, defaulting to npm");
  return "npm";
}

/**
 * Returns the COPY instruction for package.json and the detected lockfile.
 */
function copyPackageFiles(pm: PackageManager): string {
  const lockfile = LOCKFILES[pm];
  return `COPY package.json ${lockfile} ./`;
}

/**
 * Returns the install command for the detected package manager.
 */
function installCommand(pm: PackageManager): string {
  switch (pm) {
    case "npm":
      return "npm ci";
    case "yarn":
      return "yarn install --frozen-lockfile";
    case "pnpm":
      return "pnpm install --frozen-lockfile";
    case "bun":
      return "bun install --frozen-lockfile";
  }
}

/**
 * Returns the dev install command (includes dev dependencies).
 */
function installCommandWithDev(pm: PackageManager): string {
  switch (pm) {
    case "npm":
      return "npm ci";
    case "yarn":
      return "yarn install --frozen-lockfile";
    case "pnpm":
      return "pnpm install --frozen-lockfile";
    case "bun":
      return "bun install --frozen-lockfile";
  }
}

/**
 * Returns the build run command for the detected package manager.
 * Always uses the "build" script from package.json.
 */
function runBuild(pm: PackageManager, _buildCmd: string): string {
  switch (pm) {
    case "npm":
      return "npm run build";
    case "yarn":
      return "yarn build";
    case "pnpm":
      return "pnpm build";
    case "bun":
      return "bun run build";
  }
}

/**
 * Generates a Dockerfile for Node.js frameworks (React, Next.js, Express, NestJS, etc.)
 */
function generateNodeDockerfile(
  pm: PackageManager,
  opts: {
    nodeVersion: string;
    buildCmd: string;
    outputDir: string;
    startCmd: string;
    port: number;
    isStatic: boolean;
    framework: string;
  }
): string {
  const { nodeVersion, outputDir, startCmd, port, isStatic, framework } = opts;
  const copyDeps = copyPackageFiles(pm);
  const install = installCommand(pm);

  if (isStatic) {
    // Static output (React, Vue, etc.) — runtime only
    // The deployment pipeline already ran npm install + npm run build
    // and produced a valid dist/ folder. Just serve it with nginx.
    return `# ${framework} — Runtime-only with nginx
# Auto-generated by RYME Dockerfile generator
# Pre-built dist/ is copied from the host filesystem

FROM nginx:alpine

COPY ${outputDir} /usr/share/nginx/html
RUN chmod -R a+rX /usr/share/nginx/html

# SPA fallback: serve index.html for all routes
RUN printf 'server {\\n\
    listen 80;\\n\
    server_name _;\\n\
    root /usr/share/nginx/html;\\n\
    index index.html;\\n\
    location / {\\n\
        try_files $uri $uri/ /index.html;\\n\
    }\\n\
}\\n' > /etc/nginx/conf.d/default.conf

EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
`;
  }

  // Server-side frameworks (Express, NestJS, etc.)
  return `# ${framework} — Production build
# Auto-generated by RYME Dockerfile generator
# Package manager: ${pm} | Lockfile: ${LOCKFILES[pm]}

FROM node:${nodeVersion}-alpine
WORKDIR /app

${copyDeps}
RUN ${install}

COPY . .
ENV NODE_ENV=production
EXPOSE ${port}
CMD ${JSON.stringify(startCmd.split(" "))}
`;
}

/**
 * Generates a Dockerfile for Next.js with standalone output support.
 */
function generateNextjsDockerfile(
  pm: PackageManager,
  nodeVersion: string
): string {
  const copyDeps = copyPackageFiles(pm);
  const install = installCommand(pm);
  const build = runBuild(pm, "build");

  return `# Next.js — Multi-stage build with standalone output
# Auto-generated by RYME Dockerfile generator
# Package manager: ${pm} | Lockfile: ${LOCKFILES[pm]}

FROM node:${nodeVersion}-alpine AS deps
WORKDIR /app
${copyDeps}
RUN ${install}

FROM node:${nodeVersion}-alpine AS build
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
ENV NEXT_TELEMETRY_DISABLED=1
RUN ${build}

FROM node:${nodeVersion}-alpine AS runtime
WORKDIR /app
ENV NODE_ENV=production
ENV NEXT_TELEMETRY_DISABLED=1

# Copy standalone output if available, otherwise copy full build
COPY --from=build /app/public ./public 2>/dev/null || true
COPY --from=build /app/.next/standalone ./ 2>/dev/null || true
COPY --from=build /app/.next/static ./.next/static 2>/dev/null || true

# Fallback: if standalone mode is not configured
COPY --from=build /app/.next ./.next 2>/dev/null || true
COPY --from=build /app/node_modules ./node_modules 2>/dev/null || true
COPY --from=build /app/package.json ./package.json

EXPOSE 3000
ENV PORT=3000
ENV HOSTNAME="0.0.0.0"
CMD ["node", "server.js"]
`;
}

/**
 * Generates a Dockerfile for Python frameworks (FastAPI, Flask, Django).
 */
function generatePythonDockerfile(
  framework: string,
  port: number,
  startCmd: string
): string {
  const serverName = framework === "fastapi" ? "uvicorn" : "gunicorn";
  const cmdParts = startCmd.split(" ");

  return `# ${framework} — Python with ${serverName}
# Auto-generated by RYME Dockerfile generator

FROM python:${PYTHON_VERSION}-slim AS build
WORKDIR /app

COPY requirements*.txt ./
RUN pip install --no-cache-dir --user -r requirements.txt
${framework !== "fastapi" ? `RUN pip install --no-cache-dir --user ${serverName}` : ""}

FROM python:${PYTHON_VERSION}-slim
WORKDIR /app

COPY --from=build /root/.local /root/.local
ENV PATH=/root/.local/bin:$PATH

COPY . .
${framework === "django" ? `
# Collect static files if manage.py exists
RUN if [ -f manage.py ]; then python manage.py collectstatic --noinput 2>/dev/null || true; fi
` : ""}
EXPOSE ${port}
CMD ${JSON.stringify(cmdParts)}
`;
}

/**
 * Generates a Dockerfile for Go applications.
 */
function generateGoDockerfile(port: number): string {
  return `# Go — Multi-stage build
# Auto-generated by RYME Dockerfile generator

FROM golang:1.22-alpine AS build
WORKDIR /app
COPY go.mod go.sum ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o /app/server .

FROM alpine:latest
RUN apk --no-cache add ca-certificates
WORKDIR /root/
COPY --from=build /app/server .
EXPOSE ${port}
CMD ["./server"]
`;
}

/**
 * Generates a Dockerfile for Rust applications.
 */
function generateRustDockerfile(port: number): string {
  return `# Rust — Multi-stage build
# Auto-generated by RYME Dockerfile generator

FROM rust:latest AS build
WORKDIR /app
COPY Cargo.toml Cargo.lock ./
RUN mkdir src && echo "fn main() {}" > src/main.rs && cargo build --release && rm -rf src
COPY . .
RUN touch src/main.rs && cargo build --release

FROM debian:bookworm-slim
RUN apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/*
WORKDIR /root/
COPY --from=build /app/target/release/* /usr/local/bin/
EXPOSE ${port}
CMD ["server"]
`;
}

/**
 * Generates a Dockerfile for static HTML sites.
 */
function generateStaticDockerfile(): string {
  return `# Static HTML — Served with nginx
# Auto-generated by RYME Dockerfile generator

FROM nginx:alpine
COPY . /usr/share/nginx/html
RUN chmod -R a+rX /usr/share/nginx/html

# Remove non-web files
RUN rm -f /usr/share/nginx/html/Dockerfile \\
          /usr/share/nginx/html/.dockerignore \\
          /usr/share/nginx/html/.git* \\
          /usr/share/nginx/html/.env*

EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
`;
}

/**
 * Generates a generic fallback Dockerfile.
 */
function generateGenericDockerfile(
  pm: PackageManager,
  nodeVersion: string
): string {
  const copyDeps = copyPackageFiles(pm);
  const install = installCommandWithDev(pm);

  return `# Generic application — Fallback Dockerfile
# Auto-generated by RYME Dockerfile generator
# Package manager: ${pm} | Lockfile: ${LOCKFILES[pm]}

FROM node:${nodeVersion}-alpine
WORKDIR /app

${copyDeps}
RUN ${install}

COPY . .
ENV NODE_ENV=production
EXPOSE 3000

# Try common entry points
CMD ["sh", "-c", "node $([ -f server.js ] && echo server.js || ([ -f app.js ] && echo app.js || ([ -f src/index.js ] && echo src/index.js || echo index.js)))"]
`;
}

/**
 * DockerfileGenerator creates Dockerfiles dynamically for projects that don't have one.
 *
 * Instead of reading static templates, it:
 * 1. Detects which lockfile exists in the workspace
 * 2. Generates the COPY instruction based on the actual lockfile
 * 3. Generates framework-specific Dockerfiles based on package manager
 * 4. Falls back to a generic template if the framework is unknown
 *
 * Never fails — always produces a usable Dockerfile.
 */
export class DockerfileGenerator {
  /**
   * Generates a Dockerfile for the given framework and writes it to the project.
   *
   * @param framework - The detected framework name (e.g., "react", "nextjs")
   * @param projectPath - Absolute path to the project directory
   * @param options - Generation options
   * @returns The Dockerfile content that was written
   */
  async generate(
    framework: string,
    projectPath: string,
    options: GenerateOptions = {}
  ): Promise<string> {
    const nodeVersion = options.nodeVersion || NODE_VERSION_DEFAULT;
    const port = options.port || 3000;
    const buildCmd = options.buildCommand || "build";
    const outputDir = options.outputDirectory || "dist";
    const startCmd = options.startCommand || "node index.js";

    // Detect which lockfile actually exists in the workspace
    const pm = options.packageManager as PackageManager || await detectLockfile(projectPath);
    const lockfile = LOCKFILES[pm];

    logger.info(
      {
        framework,
        packageManager: pm,
        lockfile,
        nodeVersion,
        buildCmd,
        outputDir,
        startCmd,
        port,
      },
      "Generating Dockerfile"
    );

    // Generate framework-specific Dockerfile
    let dockerfile: string;

    switch (framework) {
      case "nextjs":
        dockerfile = generateNextjsDockerfile(pm, nodeVersion);
        break;

      // Static frontend frameworks — multi-stage with nginx
      case "react":
      case "react-vite":
      case "react-cra":
      case "vue":
      case "vue-vite":
      case "nuxt":
      case "svelte":
      case "sveltekit":
      case "angular":
      case "astro":
        dockerfile = generateNodeDockerfile(pm, {
          nodeVersion,
          buildCmd,
          outputDir,
          startCmd,
          port: 80,
          isStatic: true,
          framework,
        });
        break;

      // Server-side Node.js frameworks
      case "express":
      case "nestjs":
      case "node":
        dockerfile = generateNodeDockerfile(pm, {
          nodeVersion,
          buildCmd,
          outputDir,
          startCmd,
          port,
          isStatic: false,
          framework,
        });
        break;

      case "fastapi":
      case "flask":
      case "django":
      case "python":
        dockerfile = generatePythonDockerfile(framework, port, startCmd);
        break;

      case "go":
        dockerfile = generateGoDockerfile(port);
        break;

      case "rust":
        dockerfile = generateRustDockerfile(port);
        break;

      case "static":
        dockerfile = generateStaticDockerfile();
        break;

      default:
        dockerfile = generateGenericDockerfile(pm, nodeVersion);
        logger.warn(
          { framework },
          "Unknown framework, using generic Dockerfile"
        );
        break;
    }

    // Write Dockerfile to project directory
    const dockerfilePath = path.join(projectPath, "Dockerfile");
    await fs.writeFile(dockerfilePath, dockerfile, "utf-8");

    // Write .dockerignore if it doesn't exist
    await this.writeDockerignore(projectPath);

    logger.info(
      {
        framework,
        dockerfilePath,
        packageManager: pm,
        lockfile,
        copyInstruction: `COPY package.json ${lockfile} ./`,
      },
      "Dockerfile generated successfully"
    );

    return dockerfile;
  }

  /**
   * Writes a .dockerignore file if one doesn't already exist.
   */
  private async writeDockerignore(projectPath: string): Promise<void> {
    const dockerignorePath = path.join(projectPath, ".dockerignore");
    try {
      await fs.access(dockerignorePath);
    } catch {
      const dockerignore = [
        "node_modules",
        ".git",
        ".gitignore",
        ".env",
        ".env.*",
        "*.md",
        ".vscode",
        ".idea",
        "dist",
        "build",
        "coverage",
        "__pycache__",
        "*.pyc",
        ".tox",
        ".mypy_cache",
        "target/debug",
        "target/.fingerprint",
        "target/.rustc_info.json",
      ].join("\n");
      await fs.writeFile(dockerignorePath, dockerignore, "utf-8");
    }
  }
}

export const dockerfileGenerator = new DockerfileGenerator();
